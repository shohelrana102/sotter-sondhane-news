-- Supabase Dashboard → SQL Editor → New query → paste and Run.
-- This schema creates public news submissions, moderation roles, RLS and duplicate checking.
create extension if not exists pg_trgm with schema extensions;

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 5 and 180),
  body text not null check (char_length(body) between 20 and 12000),
  author text not null check (char_length(author) between 2 and 80),
  phone text not null default '',
  image_url text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
create index if not exists news_status_created_idx on public.news(status,created_at desc);

create table if not exists public.portal_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.news enable row level security;
alter table public.portal_admins enable row level security;

create or replace function public.is_portal_admin()
returns boolean language sql stable security definer
set search_path = '' as $$
  select exists(select 1 from public.portal_admins where user_id = (select auth.uid()));
$$;
revoke all on function public.is_portal_admin() from public;
grant execute on function public.is_portal_admin() to authenticated;

drop policy if exists "Anyone can read approved news" on public.news;
create policy "Anyone can read approved news" on public.news
for select to anon, authenticated using (status = 'approved' or public.is_portal_admin());

drop policy if exists "Admins can update news" on public.news;
create policy "Admins can update news" on public.news
for update to authenticated using (public.is_portal_admin()) with check (public.is_portal_admin());

drop policy if exists "Admins can delete news" on public.news;
create policy "Admins can delete news" on public.news
for delete to authenticated using (public.is_portal_admin());

-- Public users cannot directly insert/update/delete rows; they must use this guarded RPC.
revoke insert, update, delete on public.news from anon, authenticated;
grant select on public.news to anon, authenticated;
grant update, delete on public.news to authenticated;

create or replace function public.submit_news(
 p_title text, p_body text, p_author text,
 p_phone text default '', p_image_url text default ''
) returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  candidate text;
  matched_title text;
begin
  if p_title is null or char_length(trim(p_title)) < 5 or char_length(p_title) > 180
     or p_body is null or char_length(trim(p_body)) < 20 or char_length(p_body) > 12000
     or p_author is null or char_length(trim(p_author)) < 2 or char_length(p_author) > 80 then
    raise exception 'শিরোনাম, বিস্তারিত ও প্রতিবেদকের নাম সঠিকভাবে দিন।';
  end if;
  candidate := lower(regexp_replace(trim(p_title || ' ' || p_body), '[[:space:][:punct:]]+', ' ', 'g'));
  select n.title into matched_title
  from public.news n
  where n.created_at > now() - interval '90 days'
    and (
      lower(regexp_replace(trim(n.title || ' ' || n.body), '[[:space:][:punct:]]+', ' ', 'g')) = candidate
      or extensions.similarity(
        lower(regexp_replace(trim(n.title || ' ' || n.body), '[[:space:][:punct:]]+', ' ', 'g')),
        candidate
      ) >= 0.82
    )
  order by n.created_at desc limit 1;
  if matched_title is not null then
    raise exception 'সম্ভাব্য কপি/ডুপ্লিকেট নিউজ শনাক্ত হয়েছে। মিল পাওয়া শিরোনাম: %', matched_title;
  end if;
  insert into public.news(title,body,author,phone,image_url,status)
  values(trim(p_title),trim(p_body),trim(p_author),coalesce(left(p_phone,30),''),coalesce(left(p_image_url,500),''),'pending');
  return jsonb_build_object('ok',true,'message','নিউজ জমা হয়েছে। অ্যাডমিন অনুমোদনের পর প্রকাশিত হবে।');
end;
$$;
revoke all on function public.submit_news(text,text,text,text,text) from public;
grant execute on function public.submit_news(text,text,text,text,text) to anon, authenticated;

