-- Supabase Dashboard → SQL Editor → New query → paste and Run.

create table if not exists public.journalist_safety_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid references auth.users(id) on delete set null,
  reporter_name text not null,
  reporter_email text not null default '',
  reporter_phone text not null default '',
  report_type text not null check (report_type in ('নিরাপত্তা হুমকি','হামলা বা শারীরিক নিরাপত্তা','হয়রানি বা নজরদারি','আইনি সহায়তা','অন্যান্য')),
  incident_date date,
  incident_location text not null default '',
  description text not null check (char_length(description) between 50 and 5000),
  requested_help text not null default '',
  evidence_url text not null default '',
  consent_to_contact boolean not null default false,
  status text not null default 'new' check (status in ('new','reviewing','resolved')),
  admin_notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists journalist_safety_reports_created_idx
  on public.journalist_safety_reports(created_at desc);
create index if not exists journalist_safety_reports_status_idx
  on public.journalist_safety_reports(status, created_at desc);

alter table public.journalist_safety_reports enable row level security;

-- অভিযোগে পরিচয় ও নিরাপত্তা-সংক্রান্ত সংবেদনশীল তথ্য থাকে।
-- anon/authenticated সরাসরি কোনো row পড়তে বা পরিবর্তন করতে পারবে না।
-- কেবল যাচাইকৃত Cloudflare API service-role দিয়ে কাজ করবে।
revoke all on table public.journalist_safety_reports from anon, authenticated;
